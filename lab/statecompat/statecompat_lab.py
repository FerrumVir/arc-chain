def judge_node(expected, observed, expect_sha, expect_version, require_stable, scan_new):
    """The per-node verdict of one reopen. Pure: observed and expected are plain data."""
    checks = []

    def add(name, ok, detail=""):
        checks.append({"check": name, "ok": bool(ok), "detail": detail})

    add("process started and served /health", observed.get("started"), observed.get("start_error", ""))
    samples = observed.get("samples") or []
    last = samples[-1] if samples else {}
    health = last.get("health") or {}
    snap = last.get("snapshot_info") or {}
    add("the running executable is the expected binary (self-reported sha256)",
        bool(expect_sha) and health.get("binary_sha256") == expect_sha,
        "reported=%s expected=%s" % (health.get("binary_sha256"), expect_sha))
    add("reports the expected version", health.get("version") == expect_version,
        "reported=%s expected=%s" % (health.get("version"), expect_version))
    reopened = health.get("height")
    want = expected.get("height")
    add("height is not below the candidate's last observed height",
        isinstance(reopened, int) and isinstance(want, int) and reopened >= want,
        "reopened=%s candidate=%s" % (reopened, want))
    served = chain_of(observed.get("blocks"))
    missing, mismatched = [], []
    for height, value in expected["chain"].items():
        got = served.get(height)
        if got is None:
            missing.append(height)
        elif got != value:
            mismatched.append(height)
    add("every block the candidate served is served identically (hash and state root)",
        bool(expected["chain"]) and not missing and not mismatched,
        "compared=%d missing=%s mismatched=%s" % (len(expected["chain"]), missing[:5], mismatched[:5]))
    snap_height = snap.get("height")
    snap_root = norm_hex(snap.get("state_root"))
    stored = served.get(snap_height) if isinstance(snap_height, int) else None
    add("live state root equals the stored header state root at that height",
        stored is not None and snap_root is not None and stored[1] == snap_root,
        "height=%s live=%s stored=%s" % (snap_height, snap_root, stored[1] if stored else None))
    if expected.get("snapshot_height") is not None and snap_height == expected["snapshot_height"]:
        add("live state root equals the candidate's own live root at the same height",
            snap_root == expected["snapshot_root"], "reopened=%s candidate=%s" % (snap_root, expected["snapshot_root"]))
    tip_hash = norm_hex((last.get("network_info") or {}).get("last_block_hash"))
    tip_height = (last.get("network_info") or {}).get("last_block_height")
    tip_block = served.get(tip_height) if isinstance(tip_height, int) else None
    add("reported tip hash equals the served block hash at the tip",
        tip_block is not None and tip_block[0] == tip_hash, "tip=%s" % tip_height)
    if require_stable:
        views = set()
        for sample in samples:
            h = sample.get("health") or {}
            i = sample.get("network_info") or {}
            s = sample.get("snapshot_info") or {}
            views.add((h.get("height"), i.get("last_block_height"), norm_hex(i.get("last_block_hash")),
                       s.get("height"), norm_hex(s.get("state_root"))))
        add("state is stable across samples (nothing was committed or rewritten while open)",
            len(samples) >= 2 and len(views) == 1, "distinct views=%d samples=%d" % (len(views), len(samples)))
        add("no consensus engine was running (signing off)", health.get("chain_participation_enabled") is False,
            "chain_participation_enabled=%s" % health.get("chain_participation_enabled"))
    add("clean exit on SIGTERM", observed.get("exit_code") == 0, "exit=%s" % observed.get("exit_code"))
    add("no error or damage signatures beyond the control run's", not scan_new, "new=%s" % scan_new[:3])
    return {"port": expected.get("port"), "ok": all(c["ok"] for c in checks), "checks": checks}


def cross_node_agreement(observed_nodes):
    """On every height served by all nodes, hash and state root are identical on all of them."""
    chains = [chain_of(n.get("blocks")) for n in observed_nodes if n.get("started")]
    if len(chains) < 2:
        return {"ok": False, "detail": "fewer than two nodes served blocks"}
    common = set(chains[0])
    for chain in chains[1:]:
        common &= set(chain)
    bad = [h for h in sorted(common) if len(set(c[h] for c in chains)) != 1]
    return {"ok": bool(common) and not bad, "common_heights": len(common), "disagreements": bad[:10]}


def judge_reopen(expected_nodes, observed_nodes, expect_sha, expect_version, require_stable, scans, control_scans):
    by_port = {n.get("port"): n for n in observed_nodes}
    verdicts = []
    for expected in expected_nodes:
        observed = by_port.get(expected["port"]) or {"started": False, "start_error": "no result for this node"}
        scan = scans.get(expected["port"])
        control = control_scans.get(expected["port"]) if control_scans else None
        new = new_signatures(scan, control) if scan else ["no log was captured"]
        verdicts.append(judge_node(expected, observed, expect_sha, expect_version, require_stable, new))
    if len(expected_nodes) > 1:
        agreement = cross_node_agreement(list(by_port.values()))
    else:
        agreement = {"ok": True, "detail": "single node: cross-node agreement not applicable"}
    return {"ok": all(v["ok"] for v in verdicts) and agreement["ok"], "nodes": verdicts, "agreement": agreement}


def failed_checks(verdict):
    names = []
    for node in verdict["nodes"]:
        for check in node["checks"]:
            if not check["ok"]:
                names.append(check["check"])
    return sorted(set(names))


