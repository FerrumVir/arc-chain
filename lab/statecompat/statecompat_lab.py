def cmd_probe_reopen(args):
    """Runs INSIDE the isolated namespace: starts one node, watches it, stops it, writes a result."""
    spec = read_json(args.spec)
    result = {"index": spec["index"], "port": BASE_RPC + spec["index"], "mode": spec["mode"], "started": False,
              "samples": [], "blocks": [], "exit_code": None}
    process = None
    try:
        if spec.get("isolation_override") is not None and os.environ.get("STATECOMPAT_ALLOW_TEST_OVERRIDES") == "1":
            result["isolation"] = dict(spec["isolation_override"], test_override=True)
        else:
            result["isolation"] = describe_isolation()
        argv = node_argv(spec)
        result["argv"] = argv
        kwargs = {}
        if spec.get("drop_uid") is not None and os.geteuid() == 0:
            kwargs["user"] = spec["drop_uid"]
            kwargs["group"] = spec["drop_gid"]
        log_path = Path(spec["log"])
        log_path.parent.mkdir(parents=True, exist_ok=True)
        env = dict(os.environ, RUST_LOG="info")
        with open(str(log_path), "ab") as log_file:
            process = subprocess.Popen(argv, stdout=log_file, stderr=subprocess.STDOUT, env=env, **kwargs)
            port = result["port"]
            deadline = time.time() + spec.get("start_timeout", 240)
            while time.time() < deadline:
                if process.poll() is not None:
                    result["start_error"] = "exited with status %s before serving /health" % process.returncode
                    break
                if http_json(port, "/health", timeout=3):
                    result["started"] = True
                    break
                time.sleep(1)
            else:
                result["start_error"] = "no /health within %ss" % spec.get("start_timeout", 240)
            if result["started"]:
                digest_deadline = time.time() + 150
                while time.time() < digest_deadline:
                    health = http_json(port, "/health") or {}
                    if isinstance(health.get("binary_sha256"), str):
                        break
                    time.sleep(1)
                for _ in range(spec.get("samples", 3)):
                    result["samples"].append(take_sample(port))
                    time.sleep(spec.get("sample_gap", 4))
                tip = ((result["samples"][-1].get("network_info") or {}).get("last_block_height"))
                if isinstance(tip, int):
                    result["blocks"] = dump_chain(port, tip)
            if process.poll() is None:
                process.send_signal(signal.SIGTERM)
                try:
                    result["exit_code"] = process.wait(timeout=60)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
                    result["exit_code"] = "killed after 60 s without exiting on SIGTERM"
            else:
                result["exit_code"] = process.returncode
    except Exception as exc:  # recorded, never swallowed
        result["probe_error"] = repr(exc)
    finally:
        if process is not None and process.poll() is None:
            process.kill()
            process.wait()
    write_json(args.out, result)
    return 0


