    # ----- driver
    def call(self, step):
        try:
            result = step()
            return result is not False
        except Exception as exc:  # recorded, never swallowed
            log("%s: %s raised %r" % (self.tier, step.__name__, exc))
            if self.steps and self.steps[-1].get("status") == "running":
                self.finish(self.steps[-1], False, error=repr(exc))
            else:
                self.steps.append({"step": step.__name__, "status": "fail", "error": repr(exc)})
            self.check("%s completed without an error" % step.__name__, False, repr(exc))
            return False

    def archive_copies(self):
        for label, path in (("pre-candidate", self.d1), ("post-candidate", self.d3)):
            size = sum(f.stat().st_size for f in Path(path).rglob("*") if f.is_file())
            if size <= 150 * 1024 * 1024:
                target = self.out / "copies" / (label + "-copy.tar.gz")
                target.parent.mkdir(parents=True, exist_ok=True)
                with tarfile.open(str(target), "w:gz") as tar:
                    tar.add(str(path), arcname=label + "-copy")
                self.digests["archive:" + label] = sha256_file(target)
            else:
                self.caveats.append("the %s copy is %d bytes and was not archived into the evidence artifact" % (label, size))

    def run(self):
        foundation = [self.s00_binaries, self.s01_fixture, self.s02_old_run, self.s03_copy_pre, self.s04_candidate, self.s05_copy_post]
        later = [self.s06_isolation, self.s07_reopen_observer, self.s08_reopen_validator, self.s09_inspectors,
                 self.s10_resume, self.s11_negatives, self.s12_pristine]
        halted = None
        for step in foundation:
            if not self.call(step):
                halted = step.__name__
                break
        if halted is None:
            for step in later:
                self.call(step)
            try:
                self.archive_copies()
            except Exception as exc:
                self.caveats.append("could not archive the copies: %r" % exc)
        else:
            skipped = foundation[foundation.index(getattr(self, halted)) + 1:] + later
            for step in skipped:
                self.steps.append({"step": step.__name__, "status": "skipped", "reason": "foundation step %s failed" % halted})
        return self.result()

    def result(self):
        gating = [name for name, row in self.checks.items() if not name.startswith("negative control")]
        failing = [name for name in gating if not self.checks[name]["ok"]]
        incomplete = [s["step"] for s in self.steps if s.get("status") in ("skipped", "running")]
        failed_steps = [s["step"] for s in self.steps if s.get("status") == "fail"]
        verdict = "pass" if not failing and not incomplete and not failed_steps else "fail"
        result = {
            "schema": SCHEMA_TIER, "tier": self.tier, "verdict": verdict, "failing_checks": failing,
            "failed_steps": failed_steps, "incomplete_steps": incomplete, "checks": self.checks, "flags": self.flags,
            "steps": self.steps, "digests": self.digests, "caveats": self.caveats,
            "not_reproduced": tier_not_reproduced(self.tier),
            "binaries": self.binaries,
            "isolation": {"method": self.isolation_name, "evidence": self.isolation_evidence},
            "fixture": self.fixture_meta, "extra_node_args": self.extra,
            "test_override_used": bool(self.test_isolation_override),
            "environment": {"python": sys.version.split()[0], "platform": sys.platform,
                            "uname": " ".join(os.uname()) if hasattr(os, "uname") else "",
                            "image": {k: os.environ.get(k) for k in ("ImageOS", "ImageVersion")}},
            "finished": now(),
        }
        reopen = {"schema": SCHEMA_REOPEN, "tier": self.tier, "verdict": verdict,
                  "runs": self.reopen_runs, "isolation": result["isolation"],
                  "delta_file": "delta-pre-to-post-candidate.json",
                  "manifest_digests": self.digests}
        write_json(self.out / "reopen-evidence.json", reopen)
        result["reopen_evidence_sha256"] = sha256_file(self.out / "reopen-evidence.json")
        write_json(self.out / "tier-result.json", result)
        return result


