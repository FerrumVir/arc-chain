def classify(rel):
    base = os.path.basename(rel)
    if base == "node.log":
        return "log"
    if base == ".arc-node.lock":
        return "lock"
    return "state"


def build_manifest(root, label):
    """Per-path record of a data directory: type, size, mode, sha256 (mtimes are deliberately excluded)."""
    root = str(root)
    rows = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        filenames.sort()
        rel_dir = os.path.relpath(dirpath, root)
        for name in list(dirnames) + list(filenames):
            full = os.path.join(dirpath, name)
            rel = name if rel_dir == "." else os.path.join(rel_dir, name)
            info = os.lstat(full)
            mode = "%04o" % (info.st_mode & 0o7777)
            if stat.S_ISLNK(info.st_mode):
                row = {"path": rel, "type": "symlink", "target": os.readlink(full), "mode": mode}
            elif stat.S_ISDIR(info.st_mode):
                row = {"path": rel, "type": "dir", "mode": mode}
            elif stat.S_ISREG(info.st_mode):
                row = {"path": rel, "type": "file", "size": info.st_size, "mode": mode, "sha256": sha256_file(full)}
            else:
                row = {"path": rel, "type": "other", "mode": mode}
            row["class"] = classify(rel)
            rows.append(row)
    rows.sort(key=lambda r: r["path"])
    state_rows = [r for r in rows if r["class"] == "state"]
    return {
        "schema": SCHEMA_MANIFEST,
        "label": label,
        "file_count": sum(1 for r in rows if r["type"] == "file"),
        "total_bytes": sum(r.get("size", 0) for r in rows),
        "tree_sha256": sha256_bytes(canonical(rows)),
        "state_tree_sha256": sha256_bytes(canonical(state_rows)),
        "rows": rows,
    }


def manifests_equal(a, b):
    return a["rows"] == b["rows"]


def kind_of(path):
    """A file 'kind': the path with node index, hex names and counters abstracted away."""
    p = re.sub(r"^node-\d+/", "node-N/", path)
    p = re.sub(r"[0-9a-fA-F]{16,}", "<hex>", p)
    p = re.sub(r"\d+", "<n>", p)
    return p


def manifest_delta(before, after):
    b = {r["path"]: r for r in before["rows"]}
    a = {r["path"]: r for r in after["rows"]}
    added = sorted(set(a) - set(b))
    removed = sorted(set(b) - set(a))
    modified = []
    unchanged = 0
    for path in sorted(set(a) & set(b)):
        ra, rb = a[path], b[path]
        same = (ra.get("sha256") == rb.get("sha256") and ra.get("target") == rb.get("target")
                and ra["mode"] == rb["mode"] and ra["type"] == rb["type"])
        if same:
            unchanged += 1
        else:
            modified.append({"path": path, "class": ra["class"], "size_before": rb.get("size"), "size_after": ra.get("size")})
    kinds_before = set(kind_of(p) for p in b if b[p]["type"] != "dir")
    kinds_after = set(kind_of(p) for p in a if a[p]["type"] != "dir")
    return {
        "added": added,
        "removed": removed,
        "modified": modified,
        "unchanged_count": unchanged,
        "new_file_kinds": sorted(kinds_after - kinds_before),
        "vanished_file_kinds": sorted(kinds_before - kinds_after),
        "state_files_added": [p for p in added if a[p]["class"] == "state" and a[p]["type"] == "file"],
        "state_files_modified": [m["path"] for m in modified if m["class"] == "state"],
    }


def directory_listing(root, limit=400):
    rows = []
    for dirpath, dirnames, filenames in os.walk(str(root)):
        dirnames.sort()
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rows.append("%s %d" % (os.path.relpath(full, str(root)), os.lstat(full).st_size))
            if len(rows) >= limit:
                return rows + ["... truncated"]
    return rows


def copy_tree(src, dst):
    need(not os.path.exists(str(dst)), "refusing to overwrite existing copy target %s" % dst)
    shutil.copytree(str(src), str(dst), symlinks=True)


