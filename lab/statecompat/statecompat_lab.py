    # ----- reopen machinery
    def expected_nodes(self, record, label="final"):
        return [expected_from_obs(n) for n in observation_by_label(record, label)["nodes"]]

    def reopen_set(self, label, data_dir, mode, nodes=None):
        """One isolated process per node, all started together, each in its own empty network namespace."""
        nodes = list(range(NODES)) if nodes is None else list(nodes)
        reopen_dir = self.out / "reopen" / label
        reopen_dir.mkdir(parents=True, exist_ok=True)
        sudo = (self.isolation_name or "").startswith("sudo")
        procs = []
        for index in nodes:
            spec = {
                "index": index, "mode": mode, "binary": str(self.old_bin),
                "data_dir": str(Path(data_dir) / ("node-%d" % index)),
                "genesis": str(self.root / "fixture" / "genesis.toml"),
                "activation": str(self.root / "fixture" / "activation.json"),
                "key_file": str(self.root / "fixture" / ("validator-%d.key.json" % index)),
                "native_runtime": self.native, "log": str(reopen_dir / ("node-%d.log" % index)),
                "start_timeout": self.start_timeout, "samples": 3, "sample_gap": self.sample_gap,
                "isolation_override": self.test_isolation_override,
                "drop_uid": os.getuid() if sudo else None, "drop_gid": os.getgid() if sudo else None,
            }
            spec_path = reopen_dir / ("spec-%d.json" % index)
            out_path = reopen_dir / ("result-%d.json" % index)
            write_json(spec_path, spec)
            command = list(self.isolation_prefix or []) + [sys.executable, str(Path(__file__).resolve()),
                                                          "probe-reopen", "--spec", str(spec_path), "--out", str(out_path)]
            procs.append((index, out_path, subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)))
        results = []
        for index, out_path, proc in procs:
            try:
                output, _ = proc.communicate(timeout=900)
            except subprocess.TimeoutExpired:
                proc.kill()
                output, _ = proc.communicate()
            (reopen_dir / ("probe-%d.out" % index)).write_bytes(output or b"")
            if out_path.exists():
                results.append(read_json(out_path))
            else:
                results.append({"index": index, "port": BASE_RPC + index, "started": False,
                                "start_error": "probe produced no result (exit %s)" % proc.returncode})
        scans = {}
        for index in nodes:
            path = reopen_dir / ("node-%d.log" % index)
            scans[BASE_RPC + index] = scan_log(path.read_text(errors="replace") if path.exists() else "")
        return results, scans

    def judged(self, label, data_dir, mode, expected, expect_sha, expect_version, baseline_scans=None, nodes=None):
        results, scans = self.reopen_set(label, data_dir, mode, nodes=nodes)
        wanted = [e for e in expected if nodes is None or (e["port"] - BASE_RPC) in nodes]
        verdict = judge_reopen(wanted, results, expect_sha, expect_version, mode == "observer", scans, baseline_scans)
        return results, scans, verdict

    def reopen_pair(self, name, mode, note):
        """The post-candidate reopen and its control on the pre-candidate copy, both by the OLD binary."""
        new_expected = self.expected_nodes(self.new_record)
        old_expected = self.expected_nodes(self.old_record)
        d_ctl = self.root / ("d4-control-" + name)
        d_post = self.root / ("d4-reopen-" + name)
        copy_tree(self.d1, d_ctl)
        copy_tree(self.d3, d_post)
        before = self.keep_manifest(build_manifest(d_post, "d4-reopen-%s-before" % name))
        # control: the old binary on the OLD state. Its own log is the baseline of what normal looks like here.
        ctl_results, ctl_scans, _ = self.judged("control-" + name, d_ctl, mode, old_expected, self.old_sha, OLD_VERSION)
        ctl_vs_old = judge_reopen(old_expected, ctl_results, self.old_sha, OLD_VERSION, mode == "observer", ctl_scans, ctl_scans)
        ctl_vs_new = judge_reopen(new_expected, ctl_results, self.old_sha, OLD_VERSION, mode == "observer", ctl_scans, ctl_scans)
        results, scans, verdict = self.judged("post-" + name, d_post, mode, new_expected, self.old_sha, OLD_VERSION,
                                              baseline_scans=ctl_scans)
        after = self.keep_manifest(build_manifest(d_post, "d4-reopen-%s-after" % name))
        moved = manifest_delta(before, after)
        signing_changed = [m["path"] for m in moved["modified"] if m["path"].endswith("consensus-signing-record.bin")]
        control_hard = sorted(set(sig for scan in ctl_scans.values() for sig in scan["hard_signatures"]))
        control_errors = sorted(set(sig for scan in ctl_scans.values() for sig in scan["error_signatures"]))
        if control_hard:
            self.flag("%s control (old binary on old state) already shows damage-class log lines: %s" % (name, control_hard[:3]))
        run = {
            "name": name, "mode": mode, "note": note, "verdict": verdict, "failed_checks": failed_checks(verdict),
            "control_vs_old_state_ok": ctl_vs_old["ok"], "control_vs_old_failed": failed_checks(ctl_vs_old),
            "control_fails_freshness": FRESHNESS in failed_checks(ctl_vs_new),
            "control_vs_candidate_failed": failed_checks(ctl_vs_new),
            "control_error_signatures": control_errors, "control_hard_signatures": control_hard,
            "files_modified_by_reopen": moved["modified"], "files_added_by_reopen": moved["added"],
            "signing_record_changed": signing_changed,
            "exit_codes": [r.get("exit_code") for r in results],
            "log_scans": {str(k): v for k, v in scans.items()},
            "control_log_scans": {str(k): v for k, v in ctl_scans.items()},
            "results_sha256": sha256_bytes(canonical(results)),
            "isolation_verified_per_node": [bool((r.get("isolation") or {}).get("isolated")) for r in results],
            "binary_reported_per_node": [((r.get("samples") or [{}])[-1].get("health") or {}).get("binary_sha256") for r in results],
            "chain_participation_per_node": [((r.get("samples") or [{}])[-1].get("health") or {}).get("chain_participation_enabled")
                                             for r in results],
        }
        write_json(self.out / "reopen" / ("evidence-%s.json" % name), run)
        self.reopen_runs[name] = run
        state_changed = [m["path"] for m in moved["modified"] if m["class"] == "state"] + \
                        [p for p in moved["added"] if classify(p) == "state"]
        if mode == "observer" and state_changed:
            self.flag("the observer reopen modified or added state files (review): %s" % state_changed[:6])
        return run

