def node_argv(spec):
    """Argument vector for one isolated reopen. No --peers: there is nobody to talk to."""
    index = spec["index"]
    argv = [
        spec["binary"],
        "--rpc", "127.0.0.1:%d" % (BASE_RPC + index),
        "--p2p-port", str(BASE_P2P + index),
        "--data-dir", spec["data_dir"],
        "--genesis", spec["genesis"],
        "--native-inference-activation", spec["activation"],
    ]
    if spec["mode"] == "observer":
        # --stake 0 and no key: the node holds only a process-ephemeral identity
        # and starts no consensus engine, so it cannot sign a block, vote or vertex.
        argv += ["--stake", "0", "--archive"]
    else:
        argv += ["--stake", str(STAKES[index]), "--validator-key-file", spec["key_file"],
                 "--recovery-epoch", "1", "--validator-set-id", "1", "--archive",
                 "--snapshot-every-blocks", "50"]
        if spec.get("native_runtime"):
            argv += ["--native-inference-runtime", "--native-inference-test-executor",
                     "--enable-native-inference-requests"]
    return argv


