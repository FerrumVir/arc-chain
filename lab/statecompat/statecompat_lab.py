def http_json(port, path, timeout=10):
    url = "http://127.0.0.1:%d%s" % (port, path)
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:
            if response.status != 200:
                return None
            return json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, ConnectionError, socket.timeout, ValueError, OSError):
        return None


def dump_chain(port, tip):
    blocks = []
    for height in range(0, tip + 1):
        block = http_json(port, "/block/%d" % height)
        if block is None:
            blocks.append({"h": height, "missing": True})
        else:
            header = block.get("header") or {}
            blocks.append({
                "h": height,
                "hash": block.get("hash"),
                "state_root": header.get("state_root"),
                "parent_hash": header.get("parent_hash"),
                "tx_count": header.get("tx_count"),
                "protocol_major": (header.get("protocol_version") or {}).get("major"),
            })
    return blocks


def chain_of(blocks):
    out = {}
    for block in blocks or []:
        if not block.get("missing"):
            out[block["h"]] = (norm_hex(block.get("hash")), norm_hex(block.get("state_root")))
    return out


