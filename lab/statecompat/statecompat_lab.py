ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
TIMESTAMP = re.compile(r"^\s*\d{4}-\d{2}-\d{2}T[\d:.]+Z\s+")
LEVEL = re.compile(r"^\s*(TRACE|DEBUG|INFO|WARN|ERROR)\b")
HARD = re.compile(
    r"panicked at|\bpanic\b|\bFATAL\b|corrupt|checksum|(?:digest|hash|state root) mismatch|"
    r"cannot (?:decode|deserialize|parse)|failed to (?:decode|deserialize|parse|load|read|open|replay)|"
    r"unsupported (?:format|version)|incompatible|invalid (?:magic|header|record|manifest|snapshot)|"
    r"unknown (?:record|tag|variant|version)|EQUIVOCATION|equivocation detected|Slash applied",
    re.IGNORECASE,
)


def log_signature(line):
    text = ANSI.sub("", line)
    text = TIMESTAMP.sub("", text)
    text = re.sub(r"0x[0-9a-fA-F]{6,}|\b[0-9a-fA-F]{16,}\b", "<hex>", text)
    text = re.sub(r"\d+", "<n>", text)
    return text.strip()[:300]


def scan_log(text):
    levels = {}
    errors, hard = set(), set()
    count = 0
    for raw in text.splitlines():
        count += 1
        line = ANSI.sub("", raw)
        match = LEVEL.match(TIMESTAMP.sub("", line))
        level = match.group(1) if match else None
        if level:
            levels[level] = levels.get(level, 0) + 1
        if level == "ERROR":
            errors.add(log_signature(line))
        if HARD.search(line):
            hard.add(log_signature(line))
    return {"lines": count, "levels": levels, "error_signatures": sorted(errors), "hard_signatures": sorted(hard)}


def new_signatures(scan, control):
    """Error/damage signatures present in `scan` that the control run did not show."""
    base = set(control["error_signatures"]) | set(control["hard_signatures"]) if control else set()
    mine = set(scan["error_signatures"]) | set(scan["hard_signatures"])
    return sorted(mine - base)


