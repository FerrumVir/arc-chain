def history_preserved(earlier, later):
    """Every block the earlier observation served is served identically by the later one, node by node."""
    problems = []
    later_by_port = {n["port"]: n for n in later["nodes"]}
    compared = 0
    for node in earlier["nodes"]:
        other = later_by_port.get(node["port"])
        if other is None:
            problems.append("port %s absent" % node["port"])
            continue
        mine, theirs = chain_of(node.get("blocks")), chain_of(other.get("blocks"))
        for height, value in mine.items():
            compared += 1
            if theirs.get(height) != value:
                problems.append("port %s height %s differs or is missing" % (node["port"], height))
                break
    return {"ok": not problems and compared > 0, "compared_blocks": compared, "problems": problems[:10]}


