def run_harness(harness, tier, step, env_extra, log_path, timeout):
    env = dict(os.environ)
    env.update({k: str(v) for k, v in env_extra.items()})
    env["LAB_STEP"] = step
    env["LAB_TIER"] = tier
    command = [str(harness), "lab_step", "--exact", "--nocapture", "--test-threads=1"]
    Path(log_path).parent.mkdir(parents=True, exist_ok=True)
    with open(str(log_path), "wb") as stream:
        process = subprocess.Popen(command, env=env, stdout=stream, stderr=subprocess.STDOUT, start_new_session=True)
        try:
            return process.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGTERM)
            try:
                process.wait(timeout=30)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
            return -999


def binary_version_line(path):
    try:
        out = subprocess.run([str(path), "--version"], capture_output=True, text=True, timeout=60)
        return (out.stdout + out.stderr).strip().splitlines()[0] if (out.stdout + out.stderr).strip() else ""
    except (OSError, subprocess.SubprocessError) as exc:
        return "unavailable: %r" % exc


def started_reports(record):
    reports = []
    for event in record.get("events", []):
        if event.get("event") == "started":
            reports.append(event["detail"])
    return reports


def binary_reports_ok(record, expect_sha, require_feature=None):
    problems = []
    reports = started_reports(record)
    if not reports:
        problems.append("no start report recorded")
    for report in reports:
        for node in report["binary_report"]:
            if node.get("binary_sha256") != expect_sha:
                problems.append("port %s reported %s" % (node.get("port"), node.get("binary_sha256")))
            if require_feature and require_feature not in (node.get("features") or []):
                problems.append("port %s lacks feature %s" % (node.get("port"), require_feature))
    return {"ok": not problems, "starts": len(reports), "problems": problems[:10]}


