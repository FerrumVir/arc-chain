    def s04_candidate(self):
        rec = self.begin("S04-candidate-run", binary=str(self.new_bin))
        self.d2 = self.root / "d2-candidate-working-copy"
        before, _, ok = self.copy_with_proof(self.d1, self.d2, "d1-pre-candidate-copy-recheck", "d2-candidate-working-copy-before-run")
        ok = ok and manifests_equal(before, self.m_pre)
        old_json = self.out / "observations" / "old_run.json"
        rc, record, complete = self.run_step("new_run", self.d2, self.new_bin, self.new_sha, [old_json], "new_run")
        self.new_record = record
        ok = ok and rc == 0 and complete
