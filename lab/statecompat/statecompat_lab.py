def norm_hex(value):
    """Block JSON carries plain hex; /network/info and /sync/snapshot/info print 0x-prefixed Display."""
    if not isinstance(value, str):
        return None
    value = value.strip().lower()
    return value[2:] if value.startswith("0x") else value


