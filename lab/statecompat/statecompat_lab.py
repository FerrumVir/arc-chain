def interface_names():
    names = []
    with open("/proc/net/dev") as stream:
        for line in stream.readlines()[2:]:
            names.append(line.split(":")[0].strip())
    return names


def bring_up_loopback():
    """SIOCSIFFLAGS on lo, so 127.0.0.1 works inside an otherwise empty network namespace."""
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        request = struct.pack("16sH", b"lo", 0)
        flags = struct.unpack("16sH", fcntl.ioctl(sock.fileno(), 0x8913, request))[1]
        fcntl.ioctl(sock.fileno(), 0x8914, struct.pack("16sH", b"lo", flags | 0x1))
    finally:
        sock.close()


def describe_isolation():
    evidence = {"netns": os.readlink("/proc/self/ns/net")}
    try:
        bring_up_loopback()
        evidence["loopback_up"] = True
    except OSError as exc:
        evidence["loopback_up"] = False
        evidence["loopback_error"] = repr(exc)
    evidence["interfaces"] = interface_names()
    try:
        with open("/proc/net/route") as stream:
            evidence["ipv4_routes"] = [line.strip() for line in stream.readlines()[1:] if line.strip()]
    except OSError as exc:
        evidence["ipv4_routes_error"] = repr(exc)
    tests = []
    for kind, target in (("tcp", ("1.1.1.1", 443)), ("udp", ("8.8.8.8", 53)), ("tcp", ("9.9.9.9", 443))):
        try:
            if kind == "tcp":
                conn = socket.create_connection(target, timeout=3)
            else:
                conn = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
                conn.connect(target)
            conn.close()
            tests.append({"target": "%s:%d" % target, "kind": kind, "reachable": True})
        except OSError as exc:
            tests.append({"target": "%s:%d" % target, "kind": kind, "reachable": False,
                          "error": os.strerror(exc.errno) if exc.errno else repr(exc)})
    evidence["outbound_tests"] = tests
    evidence["isolated"] = (evidence.get("loopback_up") is True and evidence["interfaces"] == ["lo"]
                            and not any(t["reachable"] for t in tests))
    return evidence


def isolation_prefixes():
    return [
        ("unshare --user --map-root-user --net", ["unshare", "-Urn", "--"]),
        ("sudo unshare --net (privileges dropped for the node)", ["sudo", "-n", "unshare", "-n", "--"]),
    ]


def pick_isolation():
    """The first way of getting an empty network namespace that really works on this runner."""
    probe = [sys.executable, str(Path(__file__).resolve()), "isolation-check"]
    for name, prefix in isolation_prefixes():
        try:
            result = subprocess.run(prefix + probe, capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError):
            continue
        if result.returncode == 0:
            try:
                evidence = json.loads(result.stdout)
            except ValueError:
                continue
            if evidence.get("isolated") and evidence.get("netns") != os.readlink("/proc/self/ns/net"):
                return name, prefix, evidence
    return None, None, None


def cmd_isolation_check(_args):
    print(json.dumps(describe_isolation(), sort_keys=True))
    return 0


