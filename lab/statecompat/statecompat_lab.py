    if run_id:
        summary["ci"]["run_url"] = "https://github.com/%s/actions/runs/%s" % (os.environ.get("GITHUB_REPOSITORY", REPOSITORY), run_id)
    if args.prod_binaries and Path(args.prod_binaries).exists():
        summary["production_binaries"] = read_json(args.prod_binaries)
    for path in args.build_record or []:
        if Path(path).exists():
            record = read_json(path)
            summary["lab_builds"][record["label"]] = record
    # reproducibility: release-flag lab builds against the deployed bytes
    repro = {}
    for label, prod_key in (("baseline-release-flags", "old"), ("candidate-release-flags", "new")):
        build = summary["lab_builds"].get(label.split("-")[0])
        prod = (summary.get("production_binaries") or {}).get(prod_key)
