/// What one node reports about itself: health (with its executable digest and
/// compiled features), chain identity, the live state root, and every block
/// it can serve (hash, state root, parent, tx count) from 0 to its tip.
fn observe_port(port: u16) -> Value {
    let health = get_json(port, "/health").unwrap_or(Value::Null);
    let info = get_json(port, "/network/info").unwrap_or(Value::Null);
    let snapshot = get_json(port, "/sync/snapshot/info").unwrap_or(Value::Null);
    let tip = info["last_block_height"].as_u64();
    let mut blocks = Vec::new();
    if let Some(tip) = tip {
        for h in 0..=tip {
            match get_json(port, &format!("/block/{h}")) {
                Some(b) => blocks.push(json!({
                    "h": h,
                    "hash": b["hash"],
                    "state_root": b["header"]["state_root"],
                    "parent_hash": b["header"]["parent_hash"],
                    "tx_count": b["header"]["tx_count"],
                    "protocol_major": b["header"]["protocol_version"]["major"],
                })),
                None => blocks.push(json!({ "h": h, "missing": true })),
            }
        }
    }
    json!({
        "port": port,
        "health": health,
        "network_info": info,
        "snapshot_info": snapshot,
        "blocks": blocks,
    })
}

fn observe(nodes: &[NodeProcess], label: &str) -> Value {
    let ports: Vec<u16> = nodes.iter().map(|n| n.port).collect();
    let observed: Vec<Value> = std::thread::scope(|scope| {
        let handles: Vec<_> = ports
            .iter()
            .map(|port| {
                let port = *port;
                scope.spawn(move || observe_port(port))
            })
            .collect();
        handles
            .into_iter()
            .map(|handle| handle.join().unwrap())
            .collect()
    });
    json!({
        "label": label,
        "unix": now_unix(),
        "nodes": observed,
    })
}

// ------------------------------------------------------------------- fixture ----

struct Lab {
    dir: PathBuf,
    checkpoint: PathBuf,
    genesis: PathBuf,
    activation: PathBuf,
    manifest: Hash256,
    transaction_domain: Hash256,
    activation_height: u64,
    /// Two requesters: ingress admits only the nonce valid at the next
    /// height, so two native requests can share a DAG block only when they
    /// come from different accounts.
    requesters: [KeyPair; 2],
    tuple: [Hash256; 4],
}

fn lab_requesters() -> [KeyPair; 2] {
    [requester_keypair("p5"), requester_keypair("p5-second")]
}

fn lab_tuple() -> [Hash256; 4] {
    [
        hash_bytes(b"p5-model"),
        hash_bytes(b"p5-profile"),
        hash_bytes(b"p5-generation"),
        hash_bytes(b"p5-assignment"),
    ]
}

/// The recovered fixture of `Fixture::recovered()` in the existing test:
/// a complete six-member production-shaped recovery identity. All secrets
/// and checkpoint signatures are generated for this disposable lab. The only
/// differences are that the directory is a persistent path (so later steps can
/// reload it) instead of a TempDir, and that the fixture is described by a
/// fixture.json for those later steps.
fn create_lab(dir: &Path) -> Lab {
    use arc_state::recovery::{ArcCheckpoint, RecoveryExportSpec, RecoveryValidator};
    use arc_types::inference_contract::{ValidatorMember, validator_set_commitment};
    use std::io::Write;
    std::fs::create_dir_all(dir).unwrap();
    let stakes = STAKES.to_vec();
    let requesters = lab_requesters();
    let tuple = lab_tuple();
    let mut genesis = format!(
        "[chain]\nname = \"arc-p5-paid-flow\"\nchain_id = \"0x415243\"\n\
         validator_set_complete = true\ninstance_id = \"{}\"\n\n",
        chain_instance_id()
    );
    for requester in &requesters {
        genesis.push_str(&format!(
            "[[accounts]]\naddress = \"{}\"\nbalance = 1_000_000_000_000\n\n",
            requester.address().to_hex()
        ));
    }
    for i in 0..stakes.len() {
        let v = validator_keypair(&format!("p5-validator-{i}"))
            .address()
            .to_hex();
        // Validators need canonical accounts: any of them may submit the
        // finalize transaction once it holds a supermajority certificate.
        genesis.push_str(&format!(
            "[[accounts]]\naddress = \"{v}\"\nbalance = 1_000_000_000_000\n\n"
        ));
    }
    for i in 0..stakes.len() {
        let v = validator_keypair(&format!("p5-validator-{i}"))
            .address()
            .to_hex();
        genesis.push_str(&format!(
            "[[validators]]\naddress = \"{v}\"\nstake = {}\n\n",
            stakes[i]
        ));
    }
    let genesis_path = dir.join("genesis.toml");
    std::fs::write(&genesis_path, genesis).unwrap();
    let activation = dir.join("activation.json");
    let genesis = arc_node::config::load_genesis(genesis_path.to_str().unwrap()).unwrap();
    let genesis_hash = genesis.network_hash(false).unwrap();
    let keys: Vec<_> = (0..stakes.len())
        .map(|i| validator_keypair(&format!("p5-validator-{i}")))
        .collect();
    for (i, key) in keys.iter().enumerate() {
        let KeyPair::Ed25519(secret) = key else {
            panic!("lab needs Ed25519");
        };
        let mut file = arc_crypto::secret_file::create_new_private(
            &dir.join(format!("validator-{i}.key.json")),
        )
        .unwrap();
        file.write_all(
            serde_json::json!({ "scheme": "ed25519", "secret_key": hex::encode(secret.to_bytes()),
                "public_key": hex::encode(key.public_key_bytes()), "address": key.address().to_hex() })
            .to_string()
            .as_bytes(),
        )
        .unwrap();
        file.sync_all().unwrap();
    }
    let mut funds = genesis.validated_accounts().unwrap();
    funds.push((
        arc_state::recovery::recovery_stake_reserve_address(),
        40_000_000,
    ));
    let source = arc_state::StateDB::with_genesis(&funds);
    let joins: Vec<_> = keys
        .iter()
        .enumerate()
        .map(|(i, key)| {
            let mut tx = Transaction::new_transfer(key.address(), key.address(), 0, 0);
            tx.body = TxBody::JoinValidator(arc_types::transaction::JoinValidatorBody {
                pubkey: key.public_key_bytes().try_into().unwrap(),
                initial_stake: stakes[i],
            });
            tx.tx_type = tx.body.tx_type();
            tx.sign(key).unwrap();
            tx
        })
        .collect();
    let (_, receipts) = source.execute_block(&joins, keys[0].address()).unwrap();
    assert!(receipts.iter().all(|r| r.success));
    for key in &keys {
        let mut account = source.get_account(&key.address()).unwrap();
        account.staked_balance = 0;
        source.update_account(&key.address(), account);
    }
    source.execute_block(&[], keys[0].address()).unwrap();
    let validators = keys
        .iter()
        .enumerate()
        .map(|(i, key)| RecoveryValidator {
            address: key.address(),
            public_key: key.public_key_bytes().try_into().unwrap(),
            stake: stakes[i],
        })
        .collect();
    let mut checkpoint = ArcCheckpoint::export_unsigned(
        &source,
        RecoveryExportSpec {
            chain_id: genesis.chain.chain_id.clone(),
            genesis_hash,
            source_consensus_round: 64,
            recovery_epoch: 1,
            validator_set_id: 1,
            validators,
            community_rewards_v1_activation_height: None,
            created_at_unix_ms: 1,
        },
    )
    .unwrap();
    for key in keys.iter().take(5) {
        checkpoint.add_signature(key).unwrap();
    }
    let checkpoint_path = dir.join("approved.arcchkpt");
    checkpoint.write_to(&checkpoint_path).unwrap();
    let mut members: Vec<_> = keys
        .iter()
        .enumerate()
        .map(|(i, key)| ValidatorMember::new(key.address(), stakes[i]))
        .collect();
    members.sort_by_key(|m| m.address.0);
    let context = arc_state::InferenceAdmissionContext {
        domain: InferenceDomain {
            chain_genesis: genesis_hash,
            recovery_epoch: 1,
            validator_set_hash: validator_set_commitment(&members).unwrap(),
        },
        members,
        allowed_executions: vec![arc_state::AllowedExecution {
            model_hash: tuple[0],
            profile_hash: tuple[1],
            generation_hash: tuple[2],
            assignment_hash: tuple[3],
        }],
        selection_rule: arc_state::NativeSelectionRule::SkipUsedNoncesV2,
    };
    // Plenty of actual DAG rounds for the ordinary transfer before H.
    let activation_height = checkpoint.manifest.source_height + 1 + 256;
    std::fs::write(
        &activation,
        serde_json::json!({
            "recovery_epoch": 1, "allowed_executions": context.allowed_executions,
            "selection_rule": context.selection_rule,
            "migration": arc_state::NativeMigrationRecord { chain_genesis: genesis_hash, recovery_epoch: 1,
                validator_set_id: 1, activation_height, context_commitment: context.commitment().unwrap() },
        })
        .to_string(),
    )
    .unwrap();
    let manifest = checkpoint.manifest_hash();
    let transaction_domain = checkpoint.manifest.recovery_context().domain_hash();
    std::fs::write(
        dir.join("fixture.json"),
        serde_json::to_string_pretty(&json!({
            "schema": "arc.statecompat-lab.fixture.v1",
            "nodes": NODES,
            "stakes": stakes,
            "base_rpc": BASE_RPC,
            "base_p2p": BASE_P2P,
            "manifest": manifest.to_hex(),
            "transaction_domain": transaction_domain.to_hex(),
            "activation_height": activation_height,
            "source_height": checkpoint.manifest.source_height,
            "checkpoint_signatures": 5,
            "genesis_validator_set_complete": true,
        }))
        .unwrap(),
    )
    .unwrap();
    Lab {
        dir: dir.to_path_buf(),
        checkpoint: checkpoint_path,
        genesis: genesis_path,
        activation,
        manifest,
        transaction_domain,
        activation_height,
        requesters,
        tuple,
    }
}

fn load_lab(dir: &Path) -> Lab {
    let meta: Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("fixture.json")).unwrap()).unwrap();
    Lab {
        dir: dir.to_path_buf(),
        checkpoint: dir.join("approved.arcchkpt"),
        genesis: dir.join("genesis.toml"),
        activation: dir.join("activation.json"),
        manifest: Hash256::from_hex(meta["manifest"].as_str().unwrap()).unwrap(),
        transaction_domain: Hash256::from_hex(meta["transaction_domain"].as_str().unwrap())
            .unwrap(),
        activation_height: meta["activation_height"].as_u64().unwrap(),
        requesters: lab_requesters(),
        tuple: lab_tuple(),
    }
}

impl Lab {
    /// Start node `index`, or restart it on the data directory it had. The
    /// argument vector is the existing fixture's `spawn_mode`, with the binary
    /// chosen by the caller and extra arguments appended (the production
    /// `--recovery-epoch 1 --validator-set-id 1 --archive` and
    /// `--snapshot-every-blocks 50` come in through LAB_EXTRA_ARGS).
    fn spawn(
        &self,
        bin: &Path,
        data_root: &Path,
        index: usize,
        runtime: bool,
        admit_requests: bool,
        extra: &[String],
    ) -> NodeProcess {
        let port = BASE_RPC + index as u16;
        let data_dir = data_root.join(format!("node-{index}"));
        std::fs::create_dir_all(&data_dir).unwrap();
        let peers: Vec<String> = (0..NODES)
            .filter(|j| *j != index)
            .map(|j| format!("127.0.0.1:{}", BASE_P2P + j as u16))
            .collect();
        // Appended, so a restarted node's log follows its first life's.
        let log = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(data_dir.join("node.log"))
            .unwrap();
        let mut command = Command::new(bin);
        command.args([
            "--rpc",
            &format!("127.0.0.1:{port}"),
            "--p2p-port",
            &(BASE_P2P + index as u16).to_string(),
            "--data-dir",
            data_dir.to_str().unwrap(),
            "--genesis",
            self.genesis.to_str().unwrap(),
            "--peers",
            &peers.join(","),
            "--stake",
            &STAKES[index].to_string(),
            "--native-inference-activation",
            self.activation.to_str().unwrap(),
        ]);
        command
            .arg("--validator-key-file")
            .arg(self.dir.join(format!("validator-{index}.key.json")));
        if !data_dir.join("recovery.active").exists() {
            command
                .arg("--recovery-checkpoint")
                .arg(&self.checkpoint)
                .arg("--approved-recovery-manifest-hash")
                .arg(self.manifest.to_hex());
        }
        if runtime {
            command.args([
                "--native-inference-runtime",
                "--native-inference-test-executor",
            ]);
        }
        if admit_requests {
            command.arg("--enable-native-inference-requests");
        }
        let child = command
            .args(extra)
            .env("RUST_LOG", "info")
            .stdout(log.try_clone().unwrap())
            .stderr(log)
            .spawn()
            .expect("arc-node must start");
        NodeProcess { child, port }
    }

    fn request(
        &self,
        who: usize,
        domain: InferenceDomain,
        nonce: u64,
        expires_at: u64,
    ) -> (Transaction, Hash256) {
        let tuple = self.tuple;
        let requester = &self.requesters[who];
        let input = format!("p5 input {who}/{nonce}").into_bytes();
        let job = InferenceJob {
            version: INFERENCE_CONTRACT_VERSION,
            domain,
            requester: requester.address(),
            nonce,
            model_hash: tuple[0],
            profile_hash: tuple[1],
            input_hash: hash_bytes(&input),
            generation_hash: tuple[2],
            assignment_hash: tuple[3],
            max_tokens: 8,
            max_output_bytes: 128,
            execution_price: 10,
            reserved_max_payment: 100,
            expires_at,
        };
        let request_id = job.request_id();
        let request = InferenceRequest::sign(job, requester).unwrap();
        let body = TxBody::NativeInferenceRequest(NativeInferenceRequestBody {
            request,
            input_blob: input,
        });
        let mut tx = Transaction {
            tx_type: body.tx_type(),
            from: requester.address(),
            nonce,
            body,
            fee: 0,
            gas_limit: 5_000_000,
            hash: Hash256::ZERO,
            signature: arc_crypto::signature::Signature::null(),
            sig_verified: false,
        };
        tx.sign_in_domain(requester, &self.transaction_domain)
            .unwrap();
        (tx, request_id)
    }
}

// ------------------------------------------------------------------ the steps ----

struct Ctx {
    step: String,
    tier: String,
    lab: Lab,
    bin: PathBuf,
    data: PathBuf,
    out: PathBuf,
    extra: Vec<String>,
    expected_sha: Option<String>,
    prev: Vec<Value>,
    started: u64,
    events: Vec<Value>,
    observations: Vec<Value>,
    workload: serde_json::Map<String, Value>,
}

impl Ctx {
    fn prev_step(&self, step: &str) -> Value {
        self.prev
            .iter()
            .find(|v| v["step"] == step)
            .unwrap_or_else(|| panic!("LAB_PREV has no {step} observation"))
            .clone()
    }

    fn save(&self, complete: bool) {
        let record = json!({
            "schema": SCHEMA,
            "step": self.step,
            "tier": self.tier,
            "complete": complete,
            "binary_path": self.bin.display().to_string(),
            "expected_binary_sha256": self.expected_sha,
            "extra_args": self.extra,
            "started_unix": self.started,
            "saved_unix": now_unix(),
            "events": self.events,
            "observations": self.observations,
            "workload": Value::Object(self.workload.clone()),
        });
        std::fs::write(&self.out, serde_json::to_string_pretty(&record).unwrap()).unwrap();
    }

    fn note(&mut self, name: &str, detail: Value) {
        eprintln!("[lab] {name}: {detail}");
        self.events
            .push(json!({ "event": name, "unix": now_unix(), "detail": detail }));
        self.save(false);
    }

    fn put(&mut self, key: &str, value: Value) {
        self.workload.insert(key.to_string(), value);
        self.save(false);
    }

    fn push(&mut self, key: &str, value: Value) {
        let entry = self
            .workload
            .entry(key.to_string())
            .or_insert_with(|| Value::Array(Vec::new()));
        entry.as_array_mut().unwrap().push(value);
        self.save(false);
    }

    fn start(&mut self, runtime: bool, node0_ingress: bool, label: &str) -> Vec<NodeProcess> {
        let nodes: Vec<NodeProcess> = (0..NODES)
            .map(|i| {
                self.lab.spawn(
                    &self.bin,
                    &self.data,
                    i,
                    runtime,
                    node0_ingress && i == 0,
                    &self.extra,
                )
            })
            .collect();
        wait_recovered_peers(&nodes, label);
        let reported = wait_binary_digest(&nodes, self.expected_sha.as_deref());
        self.note(
            "started",
            json!({
                "label": label,
                "runtime": runtime,
                "node0_ingress": node0_ingress,
                "binary_report": reported,
            }),
        );
        nodes
    }

    fn observe(&mut self, nodes: &[NodeProcess], label: &str) {
        let value = observe(nodes, label);
        self.observations.push(value);
        self.save(false);
    }

    fn stop(&mut self, nodes: &mut Vec<NodeProcess>, label: &str) {
        let codes = stop_nodes(nodes);
        self.note("stopped", json!({ "label": label, "exit": codes }));
        assert!(
            codes.iter().all(|c| c["success"] == true),
            "{label}: not every validator exited cleanly: {codes:?}"
        );
        nodes.clear();
    }

    /// One ordinary transfer from requester `from` to requester `to`, accepted
    /// by node `via`, committed identically on all six.
    fn transfer(
        &mut self,
        nodes: &[NodeProcess],
        from: usize,
        to: usize,
        via: usize,
        phase: &str,
    ) -> Hash256 {
        let nonce = recovered_account(nodes[via].port, self.lab.requesters[from].address()).nonce;
        let mut tx = Transaction::new_transfer(
            self.lab.requesters[from].address(),
            self.lab.requesters[to].address(),
            1,
            nonce,
        );
        tx.fee = 1;
        tx.sign_in_domain(&self.lab.requesters[from], &self.lab.transaction_domain)
            .unwrap();
        let (code, reason) = submit(nodes[via].port, &tx);
        assert_eq!(code, 200, "{phase}: ordinary transfer refused: {reason}");
        let height = recovered_commit(nodes, tx.hash, false, phase);
        self.push(
            "transfers",
            json!({ "phase": phase, "tx": tx.hash.to_hex(), "height": height, "nonce": nonce }),
        );
        tx.hash
    }

    /// One paid native request from requester `who`, admitted by node 0 only,
    /// finalized by the committee. Returns the request id.
    fn paid_request(
        &mut self,
        nodes: &[NodeProcess],
        who: usize,
        domain: InferenceDomain,
        phase: &str,
    ) -> Hash256 {
        let nonce = recovered_account(nodes[0].port, self.lab.requesters[who].address()).nonce;
        let (paid, paid_id) = self.lab.request(who, domain, nonce, 1_000_000);
        assert_eq!(
            submit(nodes[1].port, &paid).0,
            503,
            "{phase}: a node without ingress must refuse new requests"
        );
        let (code, reason) = submit(nodes[0].port, &paid);
        assert_eq!(
            code, 200,
            "{phase}: ready opted-in node refused request: {reason}"
        );
        recovered_commit(nodes, paid.hash, true, &format!("{phase}: request"));
        wait_finalized(
            &nodes.iter().collect::<Vec<_>>(),
            paid_id,
            Duration::from_secs(120),
            &format!("{phase}: native quorum finalizes"),
        );
        let path = format!("/native-inference/receipt/{}", paid_id.to_hex());
        let receipt = get_json(nodes[0].port, &path).unwrap();
        let votes = receipt["certificate_votes"].as_u64().unwrap();
        assert!(
            votes >= 4,
            "the uneven six-member committee cannot certify with fewer than four votes"
        );
        let finalized_tx =
            Hash256::from_hex(receipt["terminal_transaction"]["tx_hash"].as_str().unwrap())
                .unwrap();
        recovered_commit(nodes, finalized_tx, true, &format!("{phase}: finalization"));
        let expected = settlement(nodes[0].port, paid_id).unwrap();
        assert_eq!(
            expected.3.iter().map(|(_, amount)| amount).sum::<u64>(),
            100
        );
        for node in nodes {
            assert_eq!(settlement(node.port, paid_id).unwrap(), expected);
        }
        self.push(
            "paid_requests",
            json!({
                "phase": phase,
                "request_id": paid_id.to_hex(),
                "certificate_votes": votes,
                "settlement": serde_json::to_value(&expected).unwrap(),
            }),
        );
        paid_id
    }
}

/// Production-flag-set steps: ordinary traffic only (no native runtime).
fn run_prod(c: &mut Ctx) {
    let step = c.step.clone();
    let mut nodes = c.start(false, false, &format!("{step}: recovered start"));
    c.observe(&nodes, "start");
    match step.as_str() {
        "old_run" => {
            c.transfer(&nodes, 0, 1, 0, "ordinary transfer before activation");
            wait_activation(&nodes);
            c.transfer(&nodes, 0, 1, 1, "ordinary transfer after activation");
        }
        "new_run" => {
            c.transfer(&nodes, 0, 1, 0, "ordinary transfer under candidate (a)");
            c.transfer(&nodes, 1, 0, 2, "ordinary transfer under candidate (b)");
            let target = advance_past_snapshot(&nodes, 60, "candidate run");
            c.put("advanced_to_height", json!(target));
        }
        "resume" => {
            c.transfer(
                &nodes,
                0,
                1,
                3,
                "ordinary transfer under resumed old binary",
            );
            let target = advance_past_snapshot(&nodes, 20, "old binary resume");
            c.put("advanced_to_height", json!(target));
        }
        other => panic!("unknown step {other}"),
    }
    c.observe(&nodes, "final");
    c.stop(&mut nodes, &step);
}

/// (label, request id, recorded settlement) for every paid request the given
/// earlier observations recorded, so a later binary can be held to them.
fn requests_of(observations: &[&Value]) -> Vec<(String, Hash256, Value)> {
    let mut rows = Vec::new();
    for observation in observations {
        if let Some(list) = observation["workload"]["paid_requests"].as_array() {
            for row in list {
                rows.push((
                    row["phase"].as_str().unwrap_or("").to_string(),
                    Hash256::from_hex(row["request_id"].as_str().unwrap()).unwrap(),
                    row["settlement"].clone(),
                ));
            }
        }
    }
    rows
}

/// Native-runtime steps: the repo's recovered-v3 paid lifecycle, split
/// across binaries (old binary writes, candidate extends, old binary resumes).
fn run_native(c: &mut Ctx) {
    let step = c.step.clone();
    match step.as_str() {
        "old_run" => {
            // Phase A: no runtime, ordinary transfer, cross activation.
            let mut nodes = c.start(false, false, "old_run phase A: signed-checkpoint import");
            c.observe(&nodes, "after_import");
            c.transfer(&nodes, 0, 1, 0, "ordinary transfer before activation");
            wait_activation(&nodes);
            c.stop(&mut nodes, "old_run phase A");
            // Phase B: native runtimes, exactly one ingress node, one paid
            // request, then a refundable bounded request left Pending.
            let mut nodes = c.start(true, true, "old_run phase B: native runtimes");
            wait_runtime_ready(&nodes, true);
            let domain = domain_from_context(&nodes[0]);
            c.paid_request(&nodes, 0, domain, "paid request on the old binary");
            c.transfer(
                &nodes,
                0,
                1,
                1,
                "ordinary transfer after native finalization",
            );
            // A valid one-token job is deliberately smaller than the
            // synthetic executor's fixed two-token answer: each worker must
            // refuse the output bounds, so the request stays refundable.
            let expires = heights(&nodes).into_iter().flatten().max().unwrap() + 40;
            let nonce = recovered_account(nodes[0].port, c.lab.requesters[1].address()).nonce;
            let (mut bounded, _) = c.lab.request(1, domain, nonce, expires);
            let TxBody::NativeInferenceRequest(body) = &mut bounded.body else {
                unreachable!()
            };
            let mut job = body.request.job.clone();
            job.max_tokens = 1;
            job.max_output_bytes = 4;
            body.request = InferenceRequest::sign(job, &c.lab.requesters[1]).unwrap();
            let refund_id = body.request.job.request_id();
            bounded
                .sign_in_domain(&c.lab.requesters[1], &c.lab.transaction_domain)
                .unwrap();
            let (code, reason) = submit(nodes[0].port, &bounded);
            assert_eq!(
                code, 200,
                "bounded valid request refused before execution: {reason}"
            );
            recovered_commit(
                &nodes,
                bounded.hash,
                true,
                "bounded request before candidate",
            );
            for node in &nodes {
                assert_eq!(settlement(node.port, refund_id).unwrap().0, "Pending");
            }
            c.put("refund_request_id", json!(refund_id.to_hex()));
            c.put("refund_expires_at", json!(expires));
            c.put("domain_chain_genesis", json!(domain.chain_genesis.to_hex()));
            c.observe(&nodes, "final");
            c.stop(&mut nodes, "old_run phase B");
        }
        "new_run" => {
            let old = c.prev_step("old_run");
            let held = requests_of(&[&old]);
            let refund_id =
                Hash256::from_hex(old["workload"]["refund_request_id"].as_str().unwrap()).unwrap();
            let expires = old["workload"]["refund_expires_at"].as_u64().unwrap();
            let mut nodes = c.start(
                true,
                true,
                "candidate: native runtimes on the pre-candidate copy",
            );
            wait_runtime_ready(&nodes, true);
            c.observe(&nodes, "start");
            // What the old binary wrote must read back identically through
            // the candidate on every node.
            for (label, id, recorded) in &held {
                for node in &nodes {
                    assert_eq!(
                        &serde_json::to_value(settlement(node.port, *id).unwrap()).unwrap(),
                        recorded,
                        "candidate reads a different settlement for: {label}"
                    );
                }
            }
            for node in &nodes {
                assert_eq!(settlement(node.port, refund_id).unwrap().0, "Pending");
            }
            // The candidate executes the refund the old binary left pending.
            wait_for(
                Duration::from_secs(240),
                "candidate DAG advances to the refund height",
                || {
                    heights(&nodes)
                        .iter()
                        .all(|h| h.is_some_and(|h| h + 1 >= expires))
                },
            );
            let body =
                TxBody::NativeInferenceRefund(arc_types::transaction::NativeInferenceRefundBody {
                    request_id: refund_id.0,
                });
            let nonce = recovered_account(nodes[2].port, c.lab.requesters[1].address()).nonce;
            let mut refund = Transaction::new_transfer(
                c.lab.requesters[1].address(),
                c.lab.requesters[1].address(),
                0,
                nonce,
            );
            refund.tx_type = body.tx_type();
            refund.body = body;
            refund.gas_limit = arc_types::transaction::gas_costs::NATIVE_INFERENCE_REFUND;
            refund
                .sign_in_domain(&c.lab.requesters[1], &c.lab.transaction_domain)
                .unwrap();
            let (code, reason) = submit(nodes[2].port, &refund);
            assert_eq!(
                code, 200,
                "closed local ingress stranded an eligible refund: {reason}"
            );
            recovered_commit(&nodes, refund.hash, true, "refund under the candidate");
            for node in &nodes {
                let receipt = settlement(node.port, refund_id).unwrap();
                assert_eq!(receipt.0, "Refunded");
                assert_eq!(
                    receipt.3,
                    vec![(c.lab.requesters[1].address().to_hex(), 100)]
                );
            }
            let refunded =
                serde_json::to_value(settlement(nodes[0].port, refund_id).unwrap()).unwrap();
            c.push(
                "refunds",
                json!({ "request_id": refund_id.to_hex(), "settlement": refunded }),
            );
            // New native work written by the candidate itself.
            let domain = domain_from_context(&nodes[0]);
            c.paid_request(&nodes, 0, domain, "paid request on the candidate");
            c.transfer(&nodes, 0, 1, 1, "ordinary transfer under candidate");
            let target = advance_past_snapshot(&nodes, 60, "candidate run");
            c.put("advanced_to_height", json!(target));
            c.observe(&nodes, "final");
            c.stop(&mut nodes, "new_run");
        }
        "resume" => {
            let old = c.prev_step("old_run");
            let cand = c.prev_step("new_run");
            let held = requests_of(&[&old, &cand]);
            let refund_id = Hash256::from_hex(
                cand["workload"]["refunds"][0]["request_id"]
                    .as_str()
                    .unwrap(),
            )
            .unwrap();
            let refund_recorded = cand["workload"]["refunds"][0]["settlement"].clone();
            let mut nodes = c.start(
                true,
                true,
                "old binary resume: native runtimes on the post-candidate copy",
            );
            wait_runtime_ready(&nodes, true);
            c.observe(&nodes, "start");
            // Everything the candidate wrote must read back identically.
            for (label, id, recorded) in &held {
                for node in &nodes {
                    assert_eq!(
                        &serde_json::to_value(settlement(node.port, *id).unwrap()).unwrap(),
                        recorded,
                        "old binary reads a different settlement for: {label}"
                    );
                }
            }
            for node in &nodes {
                assert_eq!(
                    serde_json::to_value(settlement(node.port, refund_id).unwrap()).unwrap(),
                    refund_recorded,
                    "old binary reads a different refund settlement"
                );
            }
            // The old binary must resume native execution: a NEW request
            // finalizes on it.
            let domain = domain_from_context(&nodes[0]);
            c.paid_request(&nodes, 0, domain, "paid request on the resumed old binary");
            c.transfer(
                &nodes,
                0,
                1,
                3,
                "ordinary transfer on the resumed old binary",
            );
            let target = advance_past_snapshot(&nodes, 20, "old binary resume");
            c.put("advanced_to_height", json!(target));
            c.observe(&nodes, "final");
            c.stop(&mut nodes, "resume");
        }
        other => panic!("unknown step {other}"),
    }
}

fn run_step(step: &str) {
    let out = env_path("LAB_OUT");
    if step == "fixture" {
        let dir = env_path("LAB_ROOT").join("fixture");
        let lab = create_lab(&dir);
        let record = json!({
            "schema": SCHEMA,
            "step": "fixture",
            "complete": true,
            "fixture_dir": dir.display().to_string(),
            "manifest": lab.manifest.to_hex(),
            "transaction_domain": lab.transaction_domain.to_hex(),
            "activation_height": lab.activation_height,
        });
        std::fs::write(&out, serde_json::to_string_pretty(&record).unwrap()).unwrap();
        eprintln!("[lab] fixture written to {}", dir.display());
        return;
    }
    let tier = env_required("LAB_TIER");
    assert!(
        tier == "prod" || tier == "native",
        "LAB_TIER must be prod or native"
    );
    // LAB_PREV: colon-separated observation files of earlier steps.
    let prev: Vec<Value> = std::env::var("LAB_PREV")
        .unwrap_or_default()
        .split(':')
        .filter(|path| !path.is_empty())
        .map(|path| serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap())
        .collect();
    let mut ctx = Ctx {
        step: step.to_string(),
        tier: tier.clone(),
        lab: load_lab(&env_path("LAB_ROOT").join("fixture")),
        bin: env_path("LAB_BIN"),
        data: env_path("LAB_DATA"),
        out,
        extra: std::env::var("LAB_EXTRA_ARGS")
            .unwrap_or_default()
            .split_whitespace()
            .map(str::to_string)
            .collect(),
        expected_sha: std::env::var("LAB_EXPECT_SHA256")
            .ok()
            .filter(|s| !s.is_empty()),
        prev,
        started: now_unix(),
        events: Vec::new(),
        observations: Vec::new(),
        workload: serde_json::Map::new(),
    };
    ctx.note("begin", json!({ "step": step, "tier": tier }));
    if tier == "prod" {
        run_prod(&mut ctx);
    } else {
        run_native(&mut ctx);
    }
    ctx.save(true);
}

#[test]
fn lab_step() {
    let Ok(step) = std::env::var("LAB_STEP") else {
        eprintln!("LAB_STEP is not set: the STATECOMPAT lab harness does nothing");
        return;
    };
    run_step(&step);
}
