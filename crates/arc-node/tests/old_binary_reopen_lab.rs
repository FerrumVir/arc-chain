//! STATECOMPAT old-binary-reopen lab harness (v0.8.11 release lab).
//!
//! THROWAWAY BRANCH ONLY. This file exists on `statecompat-v0811-lab` and is
//! never merged. It does not change any product code.
//!
//! It drives real `arc-node` processes on the repository's own six-validator
//! recovered-v3 fixture (the one `native_multivalidator_paid_flow.rs` builds:
//! a signed ARCCHKPT checkpoint, five of six signatures, 6_666_667/6_666_666
//! stakes, `--snapshot-every-blocks 50`, `--validator-key-file`), but selects
//! the `arc-node` binary PER STEP from the environment, so that one data
//! directory can be produced by v0.8.10, extended by the v0.8.11 candidate and
//! reopened by v0.8.10 again. The existing test hard-codes
//! `CARGO_BIN_EXE_arc-node`, which cannot express that.
//!
//! Everything here is disposable lab data: validator keys, requester keys,
//! checkpoint signatures and genesis are generated by this file for this run
//! and no real network, key, address or state is read. Key material is never
//! printed. The Python driver (lab/statecompat/statecompat_lab.py) copies,
//! digests, isolates and judges; this file only runs nodes and records what
//! the nodes themselves report.
//!
//! One test function dispatches on environment variables:
//!   LAB_STEP   fixture | old_run | new_run | resume
//!   LAB_TIER   prod (no native runtime: production flag set) | native
//!              (native runtime with the deterministic test executor)
//!   LAB_ROOT   directory holding `fixture/`
//!   LAB_DATA   directory holding node-0 .. node-5 data directories
//!   LAB_BIN    arc-node binary for this step
//!   LAB_OUT    observation JSON written here (progressively; "complete")
//!   LAB_PREV   previous step's observation JSON (new_run / resume)
//!   LAB_EXPECT_SHA256  expected sha256 of LAB_BIN (nodes must report it)
//!   LAB_EXTRA_ARGS     extra node arguments, whitespace separated
//! Without LAB_STEP the test does nothing, so an ordinary `cargo test` is inert.

