    def test_kickstart_problems(self):
        pre = {"main_pid": 10, "health_ok": True, "address": "a", "bridge_node_address": "a", "bin_arc_node_sha256": "s", "version_txt": "0.7.12",
               "node_exe_sha256": "n", "legacy_fingerprint": "f", "bridge_log_reuse_count": 3}
