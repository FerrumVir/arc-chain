class FakeLab(hr.Lab):
    """A Lab whose guest is scripted. `script` maps a substring of the command to a Result or a callable."""

    def __init__(self, cfg, evidence, work, script=None):
        super().__init__(cfg, evidence, work)
        self.script = script or {}
        self.commands = []
        self.states = []
        self.epoch = 1_000_000.0
        self.samples = []

    def say(self, message):  # keep the unit test output quiet
        pass

    def guest(self, cmd, timeout=120, retries=0, log=True):
        self.commands.append(cmd)
        if log:
            self._append("commands.jsonl", {"host_epoch": 1.0, "cmd": cmd[:600], "rc": 0})
        for needle, answer in self.script.items():
            if needle in cmd:
                return answer(cmd) if callable(answer) else answer
        return hr.Result(0, "")

    def guest_epoch(self):
        self.epoch += 60
        return self.epoch

    def capture(self):
        return self.states.pop(0)

    def wait_health(self, seconds):
        return True

    def samples_tail(self, count=5):
        return list(self.samples)

    def pull_samples(self):
        pass


def state(**overrides):
    base = {name: 1 for name in hr.UPDATER_UNCHANGED_FIELDS}
    base.update({"auto_update_rolled_back": 0, "health_ok": True, "bridge_log_reuse_count": 0, "main_pid": 100})
    base.update(overrides)
    return base


class PhaseTests(unittest.TestCase):
    def make(self, profile="smoke", **script):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        cfg = json.loads(json.dumps(CONFIG))
        cfg["stage_b"]["profile"] = profile
        lab = FakeLab(cfg, Path(tmp.name) / "evidence", Path(tmp.name) / "work", script)
        return lab

    def checks(self, lab):
        path = lab.evidence / "checks-live.jsonl"
        return {json.loads(line)["id"]: json.loads(line) for line in path.read_text().splitlines()} if path.exists() else {}

    def events(self, lab):
        path = lab.evidence / "events.jsonl"
        return [json.loads(line) for line in path.read_text().splitlines()] if path.exists() else []

    def test_updaters_pass_when_nothing_changes_and_note_the_pre_flip_exit(self):
        tail = "[x] new version available: 0.7.12 → 0.7.11. Downloading.\ncurl: (22) The requested URL returned error: 404\n"
        lab = self.make(**{
            "systemctl start arc-updater": hr.Result(1, "Job for arc-updater.service failed"),
            "auto-update.log": hr.Result(0, tail),
            "systemctl show arc-updater": hr.Result(0, "Result=exit-code\nExecMainStatus=22\nActiveState=failed\n"),
        })
        lab.states = [state(), state(), state(), state()]
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_updaters()
        checks = self.checks(lab)
        self.assertEqual(checks["L05-updater-1-noop"]["result"], "PASS")
        self.assertEqual(checks["L06-updater-2-noop"]["result"], "PASS")
        self.assertIn(hr.PRE_FLIP_NOTE, checks["L05-updater-1-noop"]["detail"])
        names = [event["name"] for event in self.events(lab)]
        self.assertEqual(names.count("updater_run_1"), 1)
        self.assertEqual(names.count("updater_run_2"), 1)
        forced = [event for event in self.events(lab) if event["name"].startswith("updater_run")]
        self.assertTrue(all(event["forced"] for event in forced))

    def test_updater_fails_when_the_binary_changed(self):
        lab = self.make(**{"auto-update.log": hr.Result(0, "log")})
        lab.states = [state(), state(bin_arc_node_sha256="other"), state(), state()]
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_updaters()
        checks = self.checks(lab)
        self.assertEqual(checks["L05-updater-1-noop"]["result"], "FAIL")
        self.assertEqual(checks["L06-updater-2-noop"]["result"], "PASS")

    def test_kickstarts(self):
        lab = self.make()
        lab.t0_address = "a"
        lab.states = []
        for number in range(3):
            pre = state(address="a", bridge_node_address="a", main_pid=100 + number, bridge_log_reuse_count=number)
            post = state(address="a", bridge_node_address="a", main_pid=101 + number, bridge_log_reuse_count=number + 1)
            lab.states += [pre, post]
        # make consecutive pre states equal the previous post state, as in real life
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_kickstarts()
        checks = self.checks(lab)
        for check_id in ("L07-kickstart-1", "L08-kickstart-2", "L09-kickstart-3"):
            self.assertEqual(checks[check_id]["result"], "PASS", checks[check_id])

    def test_kickstart_identity_change_fails(self):
        lab = self.make()
        lab.t0_address = "a"
        lab.states = [state(address="a", bridge_node_address="a", bridge_log_reuse_count=0), state(address="b", bridge_node_address="a", main_pid=101, bridge_log_reuse_count=1)] * 3
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_kickstarts()
        self.assertEqual(self.checks(lab)["L07-kickstart-1"]["result"], "FAIL")

    def test_phase_wrapper_records_a_crash_as_a_failed_check_and_goes_on(self):
        lab = self.make()

        def boom():
            raise RuntimeError("kaboom")

        self.assertFalse(lab.phase("x", ("L05-updater-1-noop",), boom))
        self.assertEqual(self.checks(lab)["L05-updater-1-noop"]["result"], "FAIL")
        with self.assertRaises(hr.Fatal):
            lab.phase("y", ("L06-updater-2-noop",), boom, fatal=True)

    def test_steady_runs_until_both_durations_hold(self):
        lab = self.make()
        lab.t0_guest_epoch = 1_000_000.0 + 60
        lab.last_forced_end_guest = 1_000_000.0 + 3000
        lab.epoch = 1_000_000.0 + 3000
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_steady()
        names = [event["name"] for event in self.events(lab)]
        self.assertEqual(names[0], "steady_begin")
        self.assertEqual(names[-1], "steady_end")
        profile = lab.profile
        target = max(lab.last_forced_end_guest + profile["min_steady_s"], lab.t0_guest_epoch + profile["min_total_s"]) + 2 * profile["sample_interval_s"]
        self.assertGreaterEqual(lab.epoch, target)
        self.assertLess(lab.epoch, target + 200, "the loop must stop soon after the target")

    def test_steady_is_cut_short_by_the_deadline(self):
        lab = self.make("full")
        lab.t0_guest_epoch = 1_000_000.0
        lab.last_forced_end_guest = 1_000_000.0
        lab.deadline = 0  # already past
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_steady()
        self.assertIn("steady_cut_short_by_deadline", [event["name"] for event in self.events(lab)])

    def test_reboot_records_boot_ids_and_issues_no_start_command(self):
        boot_ids = iter(["bootA", "bootA", "bootB", "bootB"])
        lab = self.make(**{"kernel/random/boot_id": lambda cmd: hr.Result(0, next(boot_ids) + "\n"),
                           "journalctl": hr.Result(0, "journal-pre-boot.txt journal-post-boot.txt 10")})
        lab.samples = [{"boot_id": "bootB", "health_ok": True, "node_exe": "/home/arcw0/.arc/legacy-bridge/releases/v0.8.11/arc-node-linux-x86_64", "epoch": 1_000_500.0}]
        with mock.patch.object(hr.time, "sleep"):
            lab.phase_reboot()
        checks = self.checks(lab)
        self.assertEqual(checks["L10-reboot-boot-id-changed"]["result"], "PASS", checks)
        self.assertEqual(checks["L12-pre-post-boot-logs"]["result"], "PASS", checks)
        events = {event["name"]: event for event in self.events(lab)}
        self.assertTrue(events["reboot_issued"]["forced"])
        self.assertFalse(events["reboot_recovered"]["forced"])
        self.assertEqual(events["reboot_recovered"]["detail"]["boot_id_after"], "bootB")
        self.assertEqual(events["reboot_recovered"]["detail"]["first_healthy_sample_epoch"], 1_000_500.0)
        self.assertEqual(events["reboot_recovered"]["guest_epoch"], 1_000_500.0)
        self.assertEqual(lab.last_forced_end_guest, 1_000_500.0)
        for command in lab.commands:
            self.assertNotRegex(command, r"systemctl\s+(start|restart)\s[^;&|]*arc-node")

    def test_reboot_without_a_new_boot_id_fails(self):
        lab = self.make(**{"kernel/random/boot_id": hr.Result(0, "bootA\n")})
        lab.profile = dict(lab.profile, reboot_recovery_deadline_s=1)
        clock = iter(range(1000, 100000, 50))
        with mock.patch.object(hr.time, "sleep"), mock.patch.object(hr.time, "time", side_effect=lambda: next(clock)):
            with self.assertRaises(hr.Fatal):
                lab.phase_reboot()
        self.assertEqual(self.checks(lab)["L10-reboot-boot-id-changed"]["result"], "FAIL")

    def test_check_and_event_files_are_json_lines(self):
        lab = self.make()
        lab.check("L01-kvm", "t", "PASS", "d")
        lab.event("run_begin", forced=False, guest_epoch=5.0, a=1)
        self.assertEqual(self.checks(lab)["L01-kvm"]["detail"], "d")
        self.assertEqual(self.events(lab)[0]["detail"], {"a": 1})

    def test_required_ids_are_the_ids_the_evaluator_demands(self):
        self.assertEqual(
            list(hr.REQUIRED_LIVE_IDS),
            ["L01-kvm", "L02-consume-dry-run", "L03-interrupt-took-effect", "L04-interrupt-resumes", "L05-updater-1-noop", "L06-updater-2-noop",
             "L07-kickstart-1", "L08-kickstart-2", "L09-kickstart-3", "L10-reboot-boot-id-changed", "L11-stop-rollback", "L12-pre-post-boot-logs"],
        )


